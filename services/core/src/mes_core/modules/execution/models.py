from datetime import datetime
from decimal import Decimal
from typing import Any
from uuid import UUID

from sqlalchemy import CheckConstraint, ForeignKey, Index, text
from sqlalchemy.orm import Mapped, mapped_column

from mes_core.shared.db.base import Entity

SCHEMA = "execution"


class ProductionConfirmation(Entity):
    """Operation-level confirmation (yield/scrap/rework + activity times). Its id is the idempotency key sent to ERP.

    Phase 1: entered manually by a supervisor. Phase 2: produced by the operator terminal.
    """

    __tablename__ = "production_confirmation"
    __table_args__ = (
        CheckConstraint(
            "erp_sync_status IN ('PENDING','POSTED','FAILED','NOT_REQUIRED')", name="erp_sync_status"
        ),
        CheckConstraint("yield_qty >= 0 AND scrap_qty >= 0 AND rework_qty >= 0", name="quantities"),
        Index("ix_confirmation_wo", "work_order_id", "reported_at"),
        {"schema": SCHEMA},
    )

    plant_id: Mapped[UUID] = mapped_column(ForeignKey("org.plant.id"))
    work_order_id: Mapped[UUID] = mapped_column(ForeignKey("planning.work_order.id"))
    operation_id: Mapped[UUID] = mapped_column(ForeignKey("planning.work_order_operation.id"))
    equipment_id: Mapped[UUID | None] = mapped_column(ForeignKey("org.equipment.id"))
    yield_qty: Mapped[Decimal]
    scrap_qty: Mapped[Decimal]
    rework_qty: Mapped[Decimal]
    uom: Mapped[str]
    setup_min: Mapped[Decimal]
    run_min: Mapped[Decimal]
    labor_min: Mapped[Decimal]
    final: Mapped[bool]
    comment: Mapped[str | None]
    source: Mapped[str] = mapped_column(default="MANUAL")
    reported_at: Mapped[datetime]
    reported_by: Mapped[str]
    reported_by_name: Mapped[str | None]
    erp_sync_status: Mapped[str] = mapped_column(default="PENDING")
    erp_confirmation_group: Mapped[str | None]
    erp_confirmation_count: Mapped[str | None]
    erp_error: Mapped[str | None]
    erp_attempts: Mapped[int | None]
    erp_reconciled: Mapped[bool] = mapped_column(default=False)
    erp_synced_at: Mapped[datetime | None]
    # Phase 2: terminal context
    run_id: Mapped[UUID | None] = mapped_column(ForeignKey("execution.operation_run.id"))
    terminal_id: Mapped[UUID | None] = mapped_column(ForeignKey("org.terminal.id"))
    scrap_reason: Mapped[str | None]
    client_event_id: Mapped[UUID | None] = mapped_column(unique=True)


class OperationRun(Entity):
    """One operation being worked on one machine (see domain/runs.py for the state machine).

    The partial unique indexes make it impossible to have two active runs on one machine, or on one operation.
    `id` may be generated by the terminal, so an offline terminal can queue follow-up actions for a run it
    started while disconnected.
    """

    __tablename__ = "operation_run"
    __table_args__ = (
        CheckConstraint("status IN ('SETUP','RUNNING','PAUSED','ENDED')", name="status"),
        Index("uq_run_active_equipment", "equipment_id", unique=True, postgresql_where=text("status <> 'ENDED'")),
        Index("uq_run_active_operation", "operation_id", unique=True, postgresql_where=text("status <> 'ENDED'")),
        Index("ix_run_plant_status", "plant_id", "status"),
        {"schema": SCHEMA},
    )

    plant_id: Mapped[UUID] = mapped_column(ForeignKey("org.plant.id"))
    work_order_id: Mapped[UUID] = mapped_column(ForeignKey("planning.work_order.id"), index=True)
    operation_id: Mapped[UUID] = mapped_column(ForeignKey("planning.work_order_operation.id"))
    equipment_id: Mapped[UUID] = mapped_column(ForeignKey("org.equipment.id"))
    terminal_id: Mapped[UUID | None] = mapped_column(ForeignKey("org.terminal.id"))
    operator_id: Mapped[UUID] = mapped_column(ForeignKey("identity.app_user.id"))
    operator_name: Mapped[str]
    status: Mapped[str]
    paused_from: Mapped[str | None]
    pause_reason: Mapped[str | None]
    started_at: Mapped[datetime]
    phase_started_at: Mapped[datetime]
    ended_at: Mapped[datetime | None]
    setup_s: Mapped[float] = mapped_column(default=0)
    run_s: Mapped[float] = mapped_column(default=0)
    paused_s: Mapped[float] = mapped_column(default=0)
    setup_reported_s: Mapped[float] = mapped_column(default=0)
    run_reported_s: Mapped[float] = mapped_column(default=0)
    yield_qty: Mapped[Decimal] = mapped_column(default=Decimal(0))
    scrap_qty: Mapped[Decimal] = mapped_column(default=Decimal(0))


class OperationEvent(Entity):
    """Append-only log of what happened on the shop floor, as reported by the terminal."""

    __tablename__ = "operation_event"
    __table_args__ = (
        CheckConstraint(
            "event_type IN ('START_SETUP','START_RUN','START_PRODUCTION','PAUSE','RESUME','REPORT','COMPLETE','STOP')",
            name="event_type",
        ),
        Index("ix_operation_event_run", "run_id", "occurred_at"),
        {"schema": SCHEMA},
    )

    plant_id: Mapped[UUID] = mapped_column(ForeignKey("org.plant.id"))
    run_id: Mapped[UUID] = mapped_column(ForeignKey("execution.operation_run.id"))
    work_order_id: Mapped[UUID] = mapped_column(ForeignKey("planning.work_order.id"), index=True)
    operation_id: Mapped[UUID] = mapped_column(ForeignKey("planning.work_order_operation.id"))
    equipment_id: Mapped[UUID] = mapped_column(ForeignKey("org.equipment.id"))
    terminal_id: Mapped[UUID | None] = mapped_column(ForeignKey("org.terminal.id"))
    operator_id: Mapped[UUID] = mapped_column(ForeignKey("identity.app_user.id"))
    operator_name: Mapped[str]
    event_type: Mapped[str]
    reason_code: Mapped[str | None]
    note: Mapped[str | None]
    details: Mapped[dict[str, Any] | None]
    occurred_at: Mapped[datetime]  # as reported (terminal clock, may be earlier when replayed after an outage)
    recorded_at: Mapped[datetime]  # when the server received it
    client_event_id: Mapped[UUID | None] = mapped_column(unique=True)
